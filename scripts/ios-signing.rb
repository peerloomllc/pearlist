# Sign each iOS target with its own named provisioning profile.
#
#   ruby scripts/ios-signing.rb <ios/PearList.xcodeproj> <identity> <app profile> <share profile>
#   e.g. ruby scripts/ios-signing.rb ios/PearList.xcodeproj "Apple Development" "PearList Development" "PearList Share Development"
#
# The app and its share extension both ask for the App Group (see
# plugins/with-ios-share-extension.js). Xcode's wildcard team profile cannot carry
# an App Group, and automatic signing without an Apple ID signed in on the Mac
# finds nothing else, so both targets are switched to manual signing with the
# profiles made on developer.apple.com. A command-line PROVISIONING_PROFILE_SPECIFIER
# would apply one profile to every target, hence the per-target edit here.
# ios/ is regenerated by prebuild on every build, so this runs every time.
require 'xcodeproj'

path, identity, app_profile, share_profile = ARGV
abort 'usage: ios-signing.rb <project.xcodeproj> <identity> <app profile> <share profile>' unless share_profile

project = Xcodeproj::Project.open(path)
{ 'PearList' => app_profile, 'PearListShare' => share_profile }.each do |name, profile|
  target = project.targets.find { |t| t.name == name } or abort "no target #{name} in #{path}"
  target.build_configurations.each do |c|
    c.build_settings['CODE_SIGN_STYLE'] = 'Manual'
    c.build_settings['CODE_SIGN_IDENTITY'] = identity
    c.build_settings['PROVISIONING_PROFILE_SPECIFIER'] = profile
  end
  puts "#{name} -> #{profile}"
end
project.save
