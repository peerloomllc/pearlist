// Expo config plugin: which ABIs the Android build carries.
//
// The Bare runtime ships native .so addons per ABI, so a fully universal APK
// (armeabi-v7a, arm64-v8a, x86, x86_64) is ~349 MB against ~111 MB for arm64-v8a
// alone. Every modern Android phone is arm64 (Google has required 64-bit since
// 2019), so a RELEASE build has no reason to carry anything else.
//
// A DEBUG build does. Rule 15 says every install-and-test cycle starts on a
// virtual device, and an Android emulator on an x86_64 host is x86_64 - so an
// arm64-only debug APK simply cannot be installed on one. That was the real
// blocker behind the "the emulator core dumps" item filed on 2026-07-29: the
// emulator was fine, it just had nothing installable. Proven 2026-07-31 - with
// the x64 slice the worklet reaches `worklet:loaded` with no ADDON_NOT_FOUND, and
// the emulator joined a space created on the TCL as a genuine second peer.
//
// So the DEFAULT here is both slices, which is what makes `assembleDebug` produce
// something an emulator can run without anyone remembering a flag. Measured: the
// debug APK goes 93 MB -> 101 MB, which is nothing against needing a phone.
//
// RELEASE IS NARROWED BY scripts/release.sh, which passes
// `-PreactNativeArchitectures=arm64-v8a`, exactly as it already passes
// `-Pexpo.useLegacyPackaging=true` for the same kind of reason. It is done there
// and NOT here because `reactNativeArchitectures` is a single global property and
// there is no per-build-type equivalent that works: `ndk.abiFilters` is an
// accumulating Set, so adding arm64-v8a to a variant that already has both slices
// changes nothing. Tried on 2026-07-31 and measured doing nothing - the release
// APK stayed 204 MB - so do not reach for it again.
//
// A plugin rather than a build.gradle edit because android/ is gitignored and
// regenerated by `expo prebuild`. Same reason as with-compressed-debug-libs.

const { withGradleProperties } = require('expo/config-plugins')

const ABIS = 'arm64-v8a,x86_64'

module.exports = function withAndroidAbis (config) {
  return withGradleProperties(config, (cfg) => {
    const props = cfg.modResults
    const key = 'reactNativeArchitectures'
    const existing = props.find((p) => p.type === 'property' && p.key === key)
    if (existing) existing.value = ABIS
    else props.push({ type: 'property', key, value: ABIS })
    return cfg
  })
}
